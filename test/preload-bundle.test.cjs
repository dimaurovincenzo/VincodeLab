test('BrowserWindow mantiene isolamento, sandbox e artefatto preload unico', () => {
  const main = fs.readFileSync(path.join(repositoryRoot, 'electron/main.cjs'), 'utf8')
  const windowLifecycle = fs.readFileSync(path.join(repositoryRoot, 'electron/app/window-lifecycle-runtime.cjs'), 'utf8')
  assert.match(main, /preloadPath: path\.join\(__dirname, 'preload\.cjs'\)/)
  assert.match(windowLifecycle, /preload: preloadPath/)
  assert.match(windowLifecycle, /contextIsolation: true/)
  assert.match(windowLifecycle, /nodeIntegration: false/)
  assert.match(windowLifecycle, /sandbox: true/)
})
