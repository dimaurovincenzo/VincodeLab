const assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const fs = require('node:fs')
const path = require('node:path')
const test = require('node:test')
const vm = require('node:vm')

const { CANONICAL_PRELOAD_MODULES } = require('./helpers/preload-source.cjs')

const repositoryRoot = path.join(__dirname, '..')
const artifactPath = path.join(repositoryRoot, 'electron/preload.cjs')
const artifactSource = fs.readFileSync(artifactPath, 'utf8')

function loadGeneratedPreload(flags = []) {
  const calls = []
  let exposed
  const electron = {
    contextBridge: {
      exposeInMainWorld(name, value) {
        assert.equal(name, 'vincodeLab')
        exposed = value
      },
    },
    ipcRenderer: {
      invoke: (...args) => {
        calls.push(['invoke', ...args])
        return Promise.resolve({ invoked: true })
      },
      on: (...args) => calls.push(['on', ...args]),
      removeListener: (...args) => calls.push(['removeListener', ...args]),
      send: (...args) => calls.push(['send', ...args]),
    },
    webUtils: {
      getPathForFile(file) {
        return `/safe/${file.name}`
      },
    },
  }
  vm.runInNewContext(artifactSource, {
    process: { argv: ['electron', 'app', ...flags] },
    require(specifier) {
      assert.equal(specifier, 'electron')
      return electron
    },
  })
  return { api: exposed, calls }
}

test('l’artefatto runtime è deterministico e allineato alle sorgenti canoniche', () => {
  const result = spawnSync(process.execPath, ['scripts/build-preload.mjs', '--check'], {
    cwd: repositoryRoot,
    encoding: 'utf8',
  })

  assert.equal(result.status, 0, result.stderr)
  assert.match(result.stdout, /Artefatto preload allineato/)
  assert.match(artifactSource, /^\/\/ @generated by scripts\/build-preload\.mjs; source-sha256=[a-f0-9]{64}$/m)
  assert.doesNotMatch(artifactSource, /\brequire\(["']\.\.?\//)
  assert.deepEqual([...artifactSource.matchAll(/\brequire\(["']([^"']+)["']\)/g)].map((match) => match[1]), ['electron'])
})

test('le sorgenti canoniche confinano Electron all’entry e non importano API Node', () => {
  const preloadRoot = path.join(repositoryRoot, 'electron/preload')
  for (const moduleId of CANONICAL_PRELOAD_MODULES) {
    const source = fs.readFileSync(path.join(preloadRoot, ...moduleId.split('/')), 'utf8')
    assert.doesNotMatch(source, /\brequire\(['"]node:/, moduleId)
    const externalDependencies = [...source.matchAll(/\brequire\(['"]([^.'"][^'"]*)['"]\)/g)].map((match) => match[1])
    assert.deepEqual(externalDependencies, moduleId === 'index.cjs' ? ['electron'] : [], moduleId)
  }
})

