import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const preloadRoot = path.join(repositoryRoot, 'electron', 'preload')
const outputPath = path.join(repositoryRoot, 'electron', 'preload.cjs')
const entryId = 'index.cjs'
const moduleIds = Object.freeze([
  entryId,
  'public-error-restorer.cjs',
  'ipc-renderer.cjs',
  'bridges/benchmark.bridge.cjs',
  'bridges/core.bridge.cjs',
  'bridges/developer-tools.bridge.cjs',
  'bridges/github-remote.bridge.cjs',
  'bridges/data.bridge.cjs',
  'bridges/terminal.bridge.cjs',
  '../ipc/channels.cjs',
])
const moduleIdSet = new Set(moduleIds)
const requirePattern = /\brequire\((['"])([^'"]+)\1\)/gu

function normalizeSource(source) {
  return source.replace(/\r\n?/gu, '\n').replace(/\s+$/u, '') + '\n'
}

function resolveInternalModule(importerId, specifier) {
  const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(importerId), specifier))
  if (!moduleIdSet.has(resolved)) throw new Error(`Modulo preload non dichiarato: ${specifier} da ${importerId}`)
  return resolved
}

function transformModule(moduleId, source) {
  return source.replace(requirePattern, (_match, _quote, specifier) => {
    if (specifier.startsWith('.')) return `__preloadRequire(${JSON.stringify(resolveInternalModule(moduleId, specifier))})`
    if (specifier !== 'electron') throw new Error(`Dipendenza preload esterna non consentita: ${specifier} in ${moduleId}`)
    return `require(${JSON.stringify(specifier)})`
  })
}

function indent(source, spaces) {
  const prefix = ' '.repeat(spaces)
  return source.split('\n').map((line) => line ? `${prefix}${line}` : '').join('\n')
}

function buildPreloadBundle() {
  const sources = moduleIds.map((moduleId) => {
    const sourcePath = path.join(preloadRoot, ...moduleId.split('/'))
    const source = normalizeSource(fs.readFileSync(sourcePath, 'utf8'))
    return { moduleId, source, transformed: transformModule(moduleId, source) }
  })
  const digest = crypto.createHash('sha256')
    .update(sources.map(({ moduleId, source }) => `${moduleId}\0${source}`).join('\0'))
    .digest('hex')
  const factories = sources.map(({ moduleId, transformed }) => {
    const parameters = transformed.includes('module.exports') ? 'module' : ''
    return `  ${JSON.stringify(moduleId)}: (${parameters}) => {\n${indent(transformed.trimEnd(), 4)}\n  }`
  }).join(',\n')

  return `// @generated by scripts/build-preload.mjs; source-sha256=${digest}\n// Canonical sources live in electron/preload/ and electron/ipc/channels.cjs. Do not edit this runtime artifact.\n'use strict'\n\nconst __preloadModules = Object.freeze({\n${factories}\n})\nconst __preloadCache = Object.create(null)\n\nfunction __preloadRequire(moduleId) {\n  const cached = __preloadCache[moduleId]\n  if (cached) return cached.exports\n  const factory = __preloadModules[moduleId]\n  if (!factory) throw new Error('Modulo preload non disponibile.')\n  const module = { exports: {} }\n  __preloadCache[moduleId] = module\n  factory(module, module.exports)\n  return module.exports\n}\n\n__preloadRequire(${JSON.stringify(entryId)})\n`
}

const expected = buildPreloadBundle()
if (process.argv.includes('--check')) {
  const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : ''
  if (actual !== expected) {
    process.stderr.write('Artefatto preload non allineato. Esegui `npm run build:preload`.\n')
    process.exitCode = 1
  } else {
    process.stdout.write('Artefatto preload allineato alle sorgenti canoniche.\n')
  }
} else {
  const temporaryPath = `${outputPath}.tmp`
  fs.writeFileSync(temporaryPath, expected, 'utf8')
  fs.renameSync(temporaryPath, outputPath)
  process.stdout.write('Artefatto preload generato.\n')
}
